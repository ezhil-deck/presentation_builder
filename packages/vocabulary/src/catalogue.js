/**
 * The catalogue as the vocabulary's answer key (docs/PLAN-template-library.md §1.3). The Rich Slide Catalogue marks
 * every container (`data-type`) and field (`data-f`) of its 1,077 plan slides, and every header part by class; this
 * module turns one slide's measured geometry (golden/catalogue/geometry.json) plus the text of its fields (read from
 * the catalogue HTML) into identification subjects with the marks HIDDEN, so `identify()` must name each thing from
 * what is visible: boxes, sizes, weights, lines, the item grouping (`data-i`), the container's classes / rules /
 * numeral, and the text. The hidden marks come back separately as the expected answer.
 *
 * Inputs a subject carries (and only these): kind, text, sizePctH, weight, lines, bbox (% of the slide), align,
 * block (the container number), item (the item index, null for a field outside items), cells (td / th children of
 * the field), subTexts (separate text runs the field is made of, when it has no text of its own), furniture (repeated
 * at the same spot on >= 40 % of the catalogue's slides), blockCover (the share of its container its fields cover),
 * blockDataLabels (the figures its container shows outside its fields: texts matching the vocabulary's `number`
 * pattern, a 1..n numbering of the items left out). The container's `type` and the field's `f` are never read into a
 * subject.
 */
import data from './data.cjs';
import { compilePattern } from './identify.js';

/** The number of figures among a block's own texts (outside its fields), a 1..n numbering series left out. */
export function dataLabels(texts) {
  const number = compilePattern(data.vocabulary().patterns.number);
  const nums = (texts || []).filter((x) => number.test(x));
  const ord = nums
    .filter((x) => /^0?\d{1,2}\.?$/.test(x))
    .map((x) => parseInt(x, 10))
    .sort((a, b) => a - b);
  const series = ord.length > 0 && ord.every((v, i) => v === i + 1);
  return series ? nums.length - ord.length : nums.length;
}

const W = 1920;
const H = 1080;
const NAMED = { amp: '&', lt: '<', gt: '>', quot: '"', apos: "'", nbsp: ' ' };
const decode = (s) =>
  s.replace(/&(#x[0-9a-f]+|#\d+|[a-z]+);/gi, (whole, ref) => {
    if (ref[0] === '#')
      return String.fromCodePoint(
        ref[1] === 'x' || ref[1] === 'X' ? parseInt(ref.slice(2), 16) : parseInt(ref.slice(1), 10),
      );
    return NAMED[ref.toLowerCase()] ?? whole;
  });
const VOID = new Set([
  'area',
  'base',
  'br',
  'col',
  'embed',
  'hr',
  'img',
  'input',
  'link',
  'meta',
  'source',
  'track',
  'wbr',
]);
const attr = (attrs, name) => {
  const m = new RegExp(`(?:^|\\s)${name}\\s*=\\s*"([^"]*)"`).exec(attrs);
  return m ? decode(m[1]) : null;
};

/** A minimal DOM of one figure's slide HTML: {tag, attrs, children: [node | {text}]}. */
function parseDom(html) {
  const root = { tag: '#root', attrs: '', children: [], parent: null };
  let cur = root;
  let last = 0;
  const re = /<(\/?)([a-zA-Z][a-zA-Z0-9-]*)((?:[^>"']|"[^"]*"|'[^']*')*)>|<!--[\s\S]*?-->/g;
  let m;
  while ((m = re.exec(html))) {
    const txt = html.slice(last, m.index);
    if (txt) cur.children.push({ text: decode(txt) });
    last = re.lastIndex;
    if (!m[2]) continue; // comment
    const tag = m[2].toLowerCase();
    if (m[1]) {
      let n = cur;
      while (n !== root && n.tag !== tag) n = n.parent;
      if (n !== root) cur = n.parent;
    } else {
      const node = { tag, attrs: m[3], children: [], parent: cur };
      cur.children.push(node);
      if (!VOID.has(tag) && !/\/\s*$/.test(m[3])) cur = node;
    }
  }
  return root;
}
const textOf = (n) => (n.text !== undefined ? n.text : n.children.map(textOf).join(' '));
const clean = (s) => s.replace(/\s+/g, ' ').trim();
const classes = (n) => (attr(n.attrs, 'class') || '').split(/\s+/).filter(Boolean);

/**
 * Reads the catalogue HTML once: per slide id, the header texts and the text of every marked field (by "c.f.i"),
 * with its cell count and its separate text runs. `brand` = the measured root brand (geometry.rootDataset.brand):
 * the footer's brand name is generated by CSS (`.bn::before { content: var(--bname) }`), so it is read from that
 * brand's `--bname`.
 */
export function readCatalogueText(html, brand) {
  const bm = new RegExp(`:root\\[data-brand="${brand}"\\]\\{[^}]*?--bname:"([^"]*)"`).exec(html);
  const bname = bm ? bm[1] : '';
  const slides = {};
  const fig = /<figure\b[^>]*\bid="([A-Z]\d+(?:-\d+)?)"[^>]*>([\s\S]*?)<\/figure>/g;
  let m;
  while ((m = fig.exec(html))) {
    const id = m[1];
    const body = m[2].slice(0, m[2].indexOf('<figcaption') >= 0 ? m[2].indexOf('<figcaption') : undefined);
    const dom = parseDom(body);
    const out = { header: {}, fields: {}, blocks: {}, regions: [] };
    const find = (n, pred) => {
      if (n.text !== undefined) return null;
      if (pred(n)) return n;
      for (const c of n.children) {
        const r = find(c, pred);
        if (r) return r;
      }
      return null;
    };
    const slide = find(dom, (n) => classes(n).includes('slide'));
    if (!slide) continue;
    for (const child of slide.children) {
      if (child.text !== undefined) continue;
      const cls = classes(child);
      // the geometry's regions: the slide's children that are not header parts or zones, in order
      if (
        !['k', 't', 'r', 'src', 'ft', 'lg'].some((p) => cls.includes(p)) &&
        attr(child.attrs, 'data-zone') === null
      )
        out.regions.push({ text: clean(textOf(child)) });
      for (const part of ['k', 't', 'src', 'ft']) {
        if (!cls.includes(part)) continue;
        let t = clean(textOf(child));
        if (part === 'ft' && find(child, (n) => classes(n).includes('bn'))) t = clean(`${bname} ${t}`);
        out.header[part] = t;
      }
    }
    // the block's own text outside its fields (data labels, a chart title, numerals): per container number
    const unmarked = (n, c, acc) => {
      if (n.text !== undefined) {
        if (n.text.trim()) acc.push(clean(n.text));
        return;
      }
      if (attr(n.attrs, 'data-f') !== null) return;
      const d = attr(n.attrs, 'data-c');
      if (d !== null && d !== c && attr(n.attrs, 'data-type') !== null) return;
      n.children.forEach((x) => unmarked(x, c, acc));
    };
    const walk = (n) => {
      if (n.text !== undefined) return;
      if (attr(n.attrs, 'data-type') !== null) {
        const c = attr(n.attrs, 'data-c');
        n.children.forEach((x) => unmarked(x, c, (out.blocks[c] ??= [])));
      }
      const f = attr(n.attrs, 'data-f');
      if (f !== null) {
        const c = attr(n.attrs, 'data-c');
        const i = attr(n.attrs, 'data-i');
        const kids = n.children.filter((x) => x.text === undefined && clean(textOf(x)));
        const direct = n.children.some((x) => x.text !== undefined && x.text.trim());
        out.fields[`${c}.${f}.${i ?? ''}`] = {
          text: clean(textOf(n)),
          cells: n.children.filter((x) => x.tag === 'td' || x.tag === 'th').length,
          subTexts: direct ? 0 : kids.length,
        };
      }
      n.children.forEach(walk);
    };
    walk(slide);
    slides[id] = out;
  }
  return { bname, slides };
}

const pct = (b) => [(b.x / W) * 100, (b.y / H) * 100, ((b.x + b.w) / W) * 100, ((b.y + b.h) / H) * 100];
const sizeOf = (px) => (px / H) * 100;
const alignOf = (a) => (a === 'center' ? 'centre' : a === 'right' || a === 'end' ? 'right' : 'left');
const KIND = { k: 'text', t: 'text', src: 'text', ft: 'text', r: 'shape', lg: 'image' };

/** The furniture signature of a header part: kind | text (digit runs as #) | x % | y % (as anatomy.py). */
export function signature(kind, text, bbox) {
  const tx = /^(page\s*)?\d{1,3}(\s*\/\s*\d{1,3})?$/i.test(text || 'x')
    ? '#'
    : (text || '').replace(/\d+/g, '#').slice(0, 24);
  return `${kind}|${tx}|${Math.round(bbox[0])}|${Math.round(bbox[1])}`;
}

/** The signatures repeated on >= 40 % of the catalogue's slides (and under 9 % of the slide), as anatomy's batch. */
export function catalogueFurniture(geometry, text) {
  const ids = Object.keys(geometry.slides);
  const count = new Map();
  for (const id of ids) {
    const seen = new Set();
    for (const [part, h] of Object.entries(geometry.slides[id].header || {})) {
      const b = pct(h.box);
      if ((b[2] - b[0]) * (b[3] - b[1]) >= 900) continue;
      seen.add(signature(KIND[part], text.slides[id]?.header[part], b));
    }
    for (const s of seen) count.set(s, (count.get(s) || 0) + 1);
  }
  return new Set([...count].filter(([, n]) => n >= Math.max(3, 0.4 * ids.length)).map(([s]) => s));
}

/** The body size of a slide's texts as anatomy.py measures it: the size carrying most words, the largest left out. */
export function bodySize(texts) {
  const by = new Map();
  for (const t of texts) if (!t.furniture) by.set(t.sizePctH, (by.get(t.sizePctH) || 0) + (t.words || 0));
  if (by.size <= 1) return null;
  by.delete(Math.max(...by.keys()));
  let best = null;
  for (const [s, n] of by) if (best === null || n > by.get(best)) best = s;
  return best;
}

const wordsOf = (t) => ((t || '').match(/[\p{L}\p{N}_]+/gu) || []).length;

/**
 * One plan slide -> { elements, blocks, answers }. `elements` = header parts + fields as subjects of the element
 * chain; `answers` = per element its hidden mark ({header: part} or {field: f, c, i}); blocks are built after the
 * element pass by `blockSubjects` (they read the E2 terms of their fields).
 */
export function slideSubjects(id, geometry, text, furniture) {
  const g = geometry.slides[id];
  const tx = text.slides[id] || { header: {}, fields: {} };
  const elements = [];
  const answers = [];
  for (const [part, h] of Object.entries(g.header || {})) {
    const bbox = pct(h.box);
    const kind = KIND[part];
    const s = { id: `h.${part}`, kind, bbox };
    if (kind === 'text') {
      s.text = tx.header[part] ?? '';
      s.sizePctH = sizeOf(h.fontSize);
      s.weight = h.fontWeight;
      s.align = alignOf(h.textAlign);
      s.lines = 1;
    }
    if (furniture.has(signature(kind, s.text, bbox))) s.furniture = true;
    elements.push(s);
    answers.push({ header: part });
  }
  const containers = g.containers || [];
  const cover = new Map();
  const labels = new Map();
  for (const c of containers) {
    const E = c.extent || c.box;
    const fs = (g.fields || []).filter((f) => f.c === c.c);
    const area = fs.reduce((a, f) => a + f.box.w * f.box.h, 0);
    cover.set(c.c, Math.min(1, area / Math.max(1, E.w * E.h)));
    labels.set(c.c, dataLabels(tx.blocks?.[String(c.c)]));
  }
  for (const f of g.fields || []) {
    const t = tx.fields[`${f.c}.${f.f}.${f.i ?? ''}`];
    if (!t) throw new Error(`catalogue: ${id}: no text for field ${f.c}.${f.f}.${f.i}`);
    elements.push({
      id: `f.${f.c}.${f.i ?? '-'}.${elements.length}`,
      kind: 'text',
      text: t.text,
      sizePctH: sizeOf(f.fontSize),
      weight: f.fontWeight,
      lines: f.lines,
      bbox: pct(f.box),
      align: alignOf(f.textAlign),
      block: f.c,
      item: f.i ?? null,
      cells: t.cells,
      subTexts: t.subTexts,
      blockCover: cover.get(f.c),
      blockDataLabels: labels.get(f.c),
    });
    answers.push({ field: f.f, c: f.c, i: f.i ?? null });
  }
  for (const e of elements) if (typeof e.text === 'string') e.words = wordsOf(e.text);
  const bodyPctH = bodySize(elements.filter((e) => e.kind === 'text'));
  return { elements, answers, context: { aspect: W / H, bodyPctH } };
}

/**
 * The block subjects of a slide from its containers and the E2 results of its fields (`results` aligned with
 * `elements`). Fields of a block: fields / items counts, termCount / termShare (per E2 term), itemShare (share of
 * items holding a field of that term), minItemFields, labelText (the measured numeral / label of the first item),
 * headText (the first field of the first item, in reading order), listItemShare (items whose last field is made of
 * two text runs or more), itemsInRow (the items' first fields share a row), between (a rule between items), numbered
 * (the first item carries an ordinal), connector (the line along the container: {lines, crossing, orientation, inner}
 * or null; measured for every container, so it does not leak the hidden type).
 */
export function blockSubjects(id, geometry, elements, results, readsBefore) {
  const g = geometry.slides[id];
  const blocks = [];
  for (const c of g.containers || []) {
    const idx = elements.map((e, k) => k).filter((k) => elements[k].block === c.c);
    const fields = idx.map((k) => elements[k]);
    const terms = idx.map((k) => results[k].term);
    const items = [...new Set(fields.filter((f) => f.item !== null).map((f) => f.item))];
    const termCount = {};
    for (const t of terms) termCount[t] = (termCount[t] || 0) + 1;
    const termShare = Object.fromEntries(Object.entries(termCount).map(([t, n]) => [t, n / fields.length]));
    const itemShare = {};
    const perItem = items.map((i) => idx.filter((k) => elements[k].item === i));
    for (const t of Object.keys(termCount))
      itemShare[t] = items.length
        ? perItem.filter((ks) => ks.some((k) => results[k].term === t)).length / items.length
        : 0;
    const ordered = perItem.map((ks) =>
      [...ks].sort((a, b) => (readsBefore(elements[a].bbox, elements[b].bbox) ? -1 : 1)),
    );
    const first = ordered.length ? ordered[0] : idx;
    blocks.push({
      id: `c${c.c}`,
      kind: 'block',
      bbox: pct(c.extent || c.box),
      fields: fields.length,
      items: items.length,
      minItemFields: perItem.length ? Math.min(...perItem.map((ks) => ks.length)) : fields.length ? 1 : 0,
      termCount,
      termShare,
      itemShare,
      labelText: c.numeral?.text ?? null,
      headText: first.length ? elements[first[0]].text : null,
      listItemShare: ordered.length
        ? ordered.filter((ks) => (elements[ks[ks.length - 1]].subTexts || 0) >= 2).length / ordered.length
        : 0,
      itemsInRow:
        perItem.length >= 2 &&
        perItem.every((ks) => {
          const a = elements[ks[0]].bbox;
          const b = elements[perItem[0][0]].bbox;
          return Math.min(a[3], b[3]) - Math.max(a[1], b[1]) > 0;
        }),
      between: Boolean(c.rules?.between),
      numbered: Boolean(c.numbered),
      // V1: the line along the container (scripts/catalogue-geometry.mjs measureConnector, measured whatever its type)
      connector: c.connector ?? null,
    });
  }
  return blocks;
}
